// Exercises the production cleanup script against isolated fictional data only.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const project=path.resolve(__dirname,'../..');
const base=path.join(project,'test-results');fs.mkdirSync(base,{recursive:true});
const root=fs.mkdtempSync(path.join(base,'clear-data-'));
const data=path.join(root,'cn.ruc.webhelper'),outside=path.join(root,'outside');
fs.mkdirSync(path.join(data,'webview-data/Default'),{recursive:true});fs.mkdirSync(path.join(data,'.updates'));fs.mkdirSync(outside);
for(const name of ['account.enc','settings.json','devices.json','account.enc.recovery-1','.updates/new.exe'])fs.writeFileSync(path.join(data,name),'fictional');
fs.writeFileSync(path.join(outside,'keep.txt'),'outside must survive');
fs.symlinkSync(outside,path.join(data,'linked-directory'),'junction');
const cache=path.join(data,'webview-data/Default/cache');fs.writeFileSync(cache,'locked cache');
const quote=value=>"'"+value.replaceAll("'","''")+"'";
const powershell=path.join(process.env.SystemRoot,'System32/WindowsPowerShell/v1.0/powershell.exe');
const start=(script,args=[])=>spawn(powershell,['-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-WindowStyle','Hidden','-File',script,...args],{windowsHide:true,stdio:'ignore'});
const finished=child=>new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',code=>resolve(code));});
const waitFor=async test=>{const deadline=Date.now()+15000;while(!test()){if(Date.now()>deadline)throw Error('Timed out waiting for cleanup fixture');await new Promise(r=>setTimeout(r,50));}};
(async()=>{
 const lockReady=path.join(root,'lock-ready');
 const holderScript=path.join(root,'holder.ps1');
 fs.writeFileSync(holderScript,'\ufeff'+`$f=[IO.File]::Open(${quote(cache)},[IO.FileMode]::Open,[IO.FileAccess]::ReadWrite,[IO.FileShare]::None)\n[IO.File]::WriteAllText(${quote(lockReady)},'ready')\nStart-Sleep -Seconds 3\n$f.Dispose()\n`);
 const holder=start(holderScript),holderDone=finished(holder);
 await waitFor(()=>fs.existsSync(lockReady));
 const parent=spawn(process.execPath,['-e','setTimeout(()=>{},60000)'],{windowsHide:true,stdio:'ignore'});
 const parentDone=finished(parent);
 const script=path.join(root,'cleanup.ps1'),ready=path.join(root,'cleanup.ready');
 const production=fs.readFileSync(path.join(project,'src-tauri/src/cleanup.ps1'),'utf8');
 const expected="$dataDirectory = Join-Path ([Environment]::GetFolderPath('LocalApplicationData')) 'cn.ruc.webhelper'";
 assert.ok(production.includes(expected));
 fs.writeFileSync(script,'\ufeff'+production.replace(expected,'$dataDirectory = '+quote(data)));
 const child=start(script,['-ParentProcessId',String(parent.pid),'-ReadyFile',ready]),done=finished(child);
 await waitFor(()=>fs.existsSync(ready));
 assert.ok(fs.existsSync(path.join(data,'account.enc')),'Nothing is removed before the parent exits');
 assert.throws(()=>fs.readFileSync(data+'.reset'),'Cleanup holds the reset lock until completion');
 parent.kill();await parentDone;
 assert.equal(await Promise.race([done,new Promise((_,reject)=>setTimeout(()=>{child.kill();reject(Error('Cleanup timeout'));},15000))]),0);
 await holderDone;
 assert.equal(fs.existsSync(data),false,'All fictional data and cache are removed');
 assert.equal(fs.readFileSync(data+'.reset','utf8'),'complete');
 assert.equal(fs.readFileSync(path.join(outside,'keep.txt'),'utf8'),'outside must survive','Directory links never traverse outside data');
 assert.equal(fs.existsSync(script),false,'Temporary helper removes itself');
 assert.equal(fs.existsSync(ready),false);
 console.log('PASS: confirmed cleanup waits for exit, retries locked cache, deletes all fixture data, preserves linked external files, records reset and removes its helper');
})().catch(error=>{console.error(error);process.exitCode=1;});
